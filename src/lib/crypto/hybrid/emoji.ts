export function bytesToEmoji(bytes: Uint8Array): string {
  return Array.from(bytes).map((b) => EMOJI_DICT[b]).join('');
}

export function emojiToBytes(input: string): Uint8Array {
  const bytes: number[] = [];
  const cleaned = input.replace(/\uFE0F/g, '');
  const emojiArray = [...cleaned];
  for (const emoji of emojiArray) {
    const idx = EMOJI_DICT.indexOf(emoji);
    if (idx < 0) throw new Error('无效的 Emoji 字符');
    bytes.push(idx);
  }
  return new Uint8Array(bytes);
}
